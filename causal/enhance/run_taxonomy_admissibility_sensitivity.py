@dataclass(frozen=True)
class DatasetFiles:
    final_residual: Path
    gs_residual: Path | None
    schema: Path | None


class SimpleOLSResult:
    """Small fallback result object used when statsmodels is unavailable."""

    def __init__(self, names: list[str], beta: np.ndarray, covariance: np.ndarray) -> None:
        se = np.sqrt(np.maximum(np.diag(covariance), 0.0))
        t_values = np.divide(beta, se, out=np.full_like(beta, np.nan), where=se > 0)
        p_values = np.array([math.erfc(abs(t) / math.sqrt(2.0)) if np.isfinite(t) else np.nan for t in t_values])
        self.params = pd.Series(beta, index=names)
        self.bse = pd.Series(se, index=names)
        self.tvalues = pd.Series(t_values, index=names)
        self.pvalues = pd.Series(p_values, index=names)
        self._covariance = pd.DataFrame(covariance, index=names, columns=names)

    def cov_params(self) -> pd.DataFrame:
        return self._covariance


