def resolve_constructs(frame: pd.DataFrame, constructs: list[str]) -> tuple[dict[str, str], list[str]]:
    resolved: dict[str, str] = {}
    missing: list[str] = []
    for construct in constructs:
        hit = next((column for column in ALIASES[construct] if column in frame.columns), None)
        if hit is None:
            missing.append(construct)
        else:
            resolved[construct] = hit
    return resolved, missing


def infer_outcomes(frame: pd.DataFrame, dataset: str) -> list[str]:
    if dataset == "suning":
        preferred = ["res_y_click", "res_y_cart", "res_y_purchase"]
    else:
        preferred = ["res_y_purchase"]
    outcomes = [column for column in preferred if column in frame.columns]
    if outcomes:
        return outcomes
    fallback = [column for column in frame.columns if column.startswith("res_y_")]
    if not fallback:
        raise KeyError(f"{dataset}: no residual outcome column starting with res_y_ found")
    return sorted(fallback)


def support_diagnostics(values: pd.Series) -> dict:
    finite = pd.to_numeric(values, errors="coerce").replace([np.inf, -np.inf], np.nan).dropna()
    if finite.empty:
        return {
            "Estimable": False,
            "Support_Flag": "empty_treatment_residual",
            "Support_N": 0,
            "Residual_SD_Final": np.nan,
            "Residual_IQR_Final": np.nan,
            "Residual_Support_1_99_Final": np.nan,
            "Effective_Bins_10_Final": 0,
            "Min_Bin_Count_10_Final": 0,
            "Max_Bin_Share_10_Final": np.nan,
        }
    arr = finite.to_numpy(dtype=float)
    counts, _ = np.histogram(arr, bins=10)
    nonzero = counts[counts > 0]
    sd = float(np.std(arr, ddof=1)) if len(arr) > 1 else 0.0
    iqr = float(np.percentile(arr, 75) - np.percentile(arr, 25))
    width = float(np.percentile(arr, 99) - np.percentile(arr, 1))
    reasons = []
    if len(arr) < MIN_N:
        reasons.append("small_n")
    if sd < MIN_SD:
        reasons.append("low_residual_sd")
    if iqr < MIN_IQR:
        reasons.append("low_residual_iqr")
    if len(nonzero) < MIN_BINS:
        reasons.append("sparse_effective_bins")
    return {
        "Estimable": not reasons,
        "Support_Flag": "ok" if not reasons else "|".join(reasons),
        "Support_N": int(len(arr)),
        "Residual_SD_Final": sd,
        "Residual_IQR_Final": iqr,
        "Residual_Support_1_99_Final": width,
        "Effective_Bins_10_Final": int(len(nonzero)),
        "Min_Bin_Count_10_Final": int(nonzero.min()) if len(nonzero) else 0,
        "Max_Bin_Share_10_Final": float(counts.max() / len(arr)),
    }


def numeric_design(frame: pd.DataFrame, columns: list[str]) -> pd.DataFrame:
    return frame[columns].apply(pd.to_numeric, errors="coerce").replace([np.inf, -np.inf], np.nan)


def apply_projection(
    final: pd.DataFrame,
    gs_train: pd.DataFrame | None,
    construct_to_col: dict[str, str],
    spec: str,
    constructs: list[str],
    projection: str,
) -> tuple[pd.DataFrame, dict[str, str], str]:
    if projection == "none" or gs_train is None:
        return final.copy(), construct_to_col.copy(), "existing_final_residual_only"

    mnc = [c for c in constructs if PATHWAY[c] == "MNC"]
    mai = [c for c in constructs if PATHWAY[c] == "MAI"]
    controls = [construct_to_col[c] for c in mnc]
    targets = [construct_to_col[c] for c in mai]
    missing_train = [c for c in controls + targets if c not in gs_train.columns]
    if missing_train:
        return final.copy(), construct_to_col.copy(), "gs_training_file_missing_spec_columns"

    out = final.copy()
    mapping = construct_to_col.copy()
    train_x = numeric_design(gs_train, controls)
    final_x = numeric_design(final, controls)
    train_x.insert(0, "const", 1.0)
    final_x.insert(0, "const", 1.0)
    final_x = final_x.reindex(columns=train_x.columns, fill_value=0.0)
    for construct, target in zip(mai, targets):
        y_train = pd.to_numeric(gs_train[target], errors="coerce").replace([np.inf, -np.inf], np.nan)
        observed = y_train.notna() & train_x.notna().all(axis=1)
        pure = f"{target}__{spec.lower().replace('-', '_')}_gs_pure_{VERSION}"
        if int(observed.sum()) <= train_x.shape[1] + 5:
            out[pure] = np.nan
            mapping[construct] = pure
            continue
        x_obs = train_x.loc[observed].to_numpy(dtype=float)
        y_obs = y_train.loc[observed].to_numpy(dtype=float)
        coef = np.linalg.pinv(x_obs.T @ x_obs) @ x_obs.T @ y_obs
        raw = pd.to_numeric(final[target], errors="coerce").to_numpy(dtype=float)
        pred = np.asarray(final_x.to_numpy(dtype=float) @ coef, dtype=float)
        out[pure] = np.where(np.isfinite(raw), raw - pred, np.nan)
        mapping[construct] = pure
    return out, mapping, "train_fitted_mnc_to_mai_projection"


def fit_hc1_ols(complete: pd.DataFrame, outcome: str, columns: list[str]) -> SimpleOLSResult:
    names = ["const", *columns]
    x = np.column_stack([np.ones(len(complete)), complete[columns].to_numpy(dtype=float)])
    y = complete[outcome].to_numpy(dtype=float)
    xtx_inv = np.linalg.pinv(x.T @ x)
    beta = xtx_inv @ x.T @ y
    residual = y - x @ beta
    meat = x.T @ ((residual[:, None] ** 2) * x)
    n, k = x.shape
    scale = n / max(1, n - k)
    covariance = scale * xtx_inv @ meat @ xtx_inv
    return SimpleOLSResult(names, beta, covariance)


def fit_clustered_ols(frame: pd.DataFrame, outcome: str, columns: list[str]):
    complete = numeric_design(frame, [outcome] + columns).dropna()
    if len(complete) <= len(columns) + 5:
        raise RuntimeError("insufficient_complete_cases")
    try:
        import statsmodels.api as sm

        x = sm.add_constant(complete[columns], has_constant="add")
        base = sm.OLS(complete[outcome], x)
        if {"cluster_user_id", "cluster_item_id"}.issubset(frame.columns):
            clusters = frame.loc[complete.index, ["cluster_user_id", "cluster_item_id"]]
            user_codes = pd.factorize(clusters["cluster_user_id"].astype(str))[0]
            item_codes = pd.factorize(clusters["cluster_item_id"].astype(str))[0]
            try:
                model = base.fit(cov_type="cluster", cov_kwds={"groups": np.column_stack([user_codes, item_codes])})
                return model, complete.index, "two_way_cluster_user_item"
            except Exception:
                model = base.fit(cov_type="cluster", cov_kwds={"groups": user_codes})
                return model, complete.index, "cluster_user"
        model = base.fit(cov_type="HC1")
        return model, complete.index, "HC1_no_cluster_ids"
    except ImportError:
        return fit_hc1_ols(complete, outcome, columns), complete.index, "HC1_fallback_no_statsmodels"


def chi2_sf(statistic: float, df: int) -> float:
    try:
        import scipy.stats as stats

        return float(stats.chi2.sf(statistic, df))
    except ImportError:
        if df == 1:
            return math.erfc(math.sqrt(max(statistic, 0.0)) / math.sqrt(2.0))
        return np.nan


def wald_test(model, columns: list[str]) -> dict:
    names = list(model.params.index)
    included = [column for column in columns if column in names]
    if not included:
        return {"Statistic": np.nan, "DF": 0, "P_Value": np.nan}
    restriction = np.zeros((len(included), len(names)), dtype=float)
    for row_idx, column in enumerate(included):
        restriction[row_idx, names.index(column)] = 1.0
    try:
        test = model.wald_test(restriction, scalar=True)
        statistic = float(np.asarray(test.statistic).squeeze())
        p_value = float(np.asarray(test.pvalue).squeeze())
    except Exception:
        cov = np.asarray(model.cov_params(), dtype=float)
        beta = np.asarray(model.params, dtype=float)
        r_beta = restriction @ beta
        r_cov = restriction @ cov @ restriction.T
        statistic = float(r_beta.T @ np.linalg.pinv(r_cov) @ r_beta)
        p_value = chi2_sf(statistic, len(included))
    return {"Statistic": statistic, "DF": int(len(included)), "P_Value": p_value}


def rank_diagnostics(frame: pd.DataFrame, columns: list[str]) -> dict:
    complete = numeric_design(frame, columns).dropna()
    if complete.empty:
        return {"Rank": 0, "Cue_Count": len(columns), "Min_Eigenvalue": np.nan, "Condition_Number": np.nan}
    corr = complete.corr().replace([np.inf, -np.inf], np.nan).fillna(0.0).to_numpy(dtype=float)
    if corr.shape[0] == 1:
        return {"Rank": 1, "Cue_Count": 1, "Min_Eigenvalue": 1.0, "Condition_Number": 1.0}
    eig = np.linalg.eigvalsh(corr)
    positive = eig[eig > 1e-10]
    condition = float(positive.max() / positive.min()) if len(positive) else np.nan
    return {
        "Rank": int(np.linalg.matrix_rank(corr)),
        "Cue_Count": int(len(columns)),
        "Min_Eigenvalue": float(eig.min()),
        "Condition_Number": condition,
    }


